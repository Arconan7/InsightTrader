export function getTradeSignals(filter?: {
  direction?: string;
  status?: string;
  ticker?: string;
  minConfidence?: number;
}): TradeSignal[] {
  let results = [...mockTradeSignals];
  if (!filter) return results;

  if (filter.direction) {
    results = results.filter((s) => s.direction === filter.direction);
  }
  if (filter.status) {
    results = results.filter((s) => s.status === filter.status);
  }
  if (filter.ticker) {
    results = results.filter((s) => s.ticker.toUpperCase() === filter.ticker?.toUpperCase());
  }
  if (filter.minConfidence !== undefined) {
    results = results.filter((s) => s.confidenceScorePct >= filter.minConfidence!);
  }
  return results;
}

